using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace ShiroBot.SDK.Generators;

/// <summary>
/// 为 [PluginContract] 生成服务和事件属性的实现、消息类型的 JSON 读写代码，并把契约源码写进程序集，
/// 供其他插件在构建时导入。[PluginJson] 类型和 PluginJsonSchema.For / PluginJson.As 等用到的类型只生成读写代码。
/// </summary>
[Generator]
public sealed class PluginContractGenerator : IIncrementalGenerator
{
    internal const string ContractMetadataKey = "ShiroBot.PluginContract";
    // 构建时按这两个标记从插件 DLL 里截出契约源码（特性参数里的字符串以 UTF-8 原样存放）。
    internal const string ContractStart = "// <shirobot-plugin-contract>";
    internal const string ContractEnd = "// </shirobot-plugin-contract>";
    private const string Sdk = "global::ShiroBot.SDK.Plugin.";
    private static readonly HashSet<string> JsonMethods = new() { "For", "As", "Serialize", "Deserialize", "ToNode", "GetMetadata" };

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var contracts = context.SyntaxProvider.ForAttributeWithMetadataName(
                "ShiroBot.SDK.Plugin.PluginContractAttribute",
                static (node, _) => node is ClassDeclarationSyntax,
                static (ctx, _) => (INamedTypeSymbol)ctx.TargetSymbol)
            .Collect();
        var jsonTypes = context.SyntaxProvider.ForAttributeWithMetadataName(
                "ShiroBot.SDK.Plugin.PluginJsonAttribute",
                static (_, _) => true,
                static (ctx, _) => (ITypeSymbol)ctx.TargetSymbol)
            .Collect();
        var usages = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is InvocationExpressionSyntax
                {
                    Expression: MemberAccessExpressionSyntax { Name: GenericNameSyntax generic }
                } && JsonMethods.Contains(generic.Identifier.Text),
                static (ctx, ct) => UsedJsonType(ctx, ct))
            .Where(static type => type is not null)
            .Collect();

        var input = contracts.Combine(jsonTypes).Combine(usages).Combine(context.CompilationProvider);
        context.RegisterSourceOutput(input, static (spc, source) =>
        {
            var (((contractSymbols, jsonSymbols), usedTypes), compilation) = source;
            Execute(spc, compilation, contractSymbols, jsonSymbols, usedTypes!);
        });
    }

    private static ITypeSymbol? UsedJsonType(GeneratorSyntaxContext context, System.Threading.CancellationToken cancellationToken)
    {
        if (context.SemanticModel.GetSymbolInfo(context.Node, cancellationToken).Symbol is not IMethodSymbol method) return null;
        var original = method.ReducedFrom ?? method;
        var owner = original.ContainingType?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        if (owner is not (Sdk + "PluginJsonSchema" or Sdk + "PluginJson" or Sdk + "PluginServiceInfo")) return null;
        return method.TypeArguments.Length == 1 ? method.TypeArguments[0] : null;
    }

    private static void Execute(SourceProductionContext context, Compilation compilation,
        ImmutableArray<INamedTypeSymbol> contractSymbols, ImmutableArray<ITypeSymbol> jsonSymbols, ImmutableArray<ITypeSymbol> usedTypes)
    {
        var catalog = new TypeCatalog(compilation);
        var contracts = new List<ContractModel>();
        foreach (var symbol in contractSymbols.Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default))
        {
            if (Contract(symbol, catalog, context) is { } contract) contracts.Add(contract);
        }
        foreach (var symbol in jsonSymbols.Concat(usedTypes).Distinct<ITypeSymbol>(SymbolEqualityComparer.Default))
        {
            if (symbol is INamedTypeSymbol { TypeKind: TypeKind.Class or TypeKind.Struct })
                catalog.Classify(symbol, false, symbol.Locations.FirstOrDefault());
        }
        foreach (var diagnostic in catalog.Diagnostics) context.ReportDiagnostic(diagnostic);
        if (contracts.Count == 0 && !catalog.Objects.Any()) return;
        if (catalog.Diagnostics.Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)) return;

        var codecs = new CodecEmitter(catalog);
        var output = new StringBuilder();
        output.AppendLine("// <auto-generated/>");
        output.AppendLine("#nullable enable");
        output.AppendLine("#pragma warning disable CS1591, CS0108, CA2255");
        output.AppendLine();

        var exported = contracts.Where(contract => contract.ImportedFrom is null).ToList();
        if (exported.Count > 0)
        {
            var source = ExportSource(exported, catalog, compilation.AssemblyName ?? "");
            output.AppendLine($"[assembly: global::System.Reflection.AssemblyMetadata({SymbolDisplay.FormatLiteral(ContractMetadataKey, true)}, {SymbolDisplay.FormatLiteral(source, true)})]");
            output.AppendLine();
        }

        foreach (var contract in contracts) EmitImplementation(output, contract, codecs);

        output.AppendLine("namespace ShiroBot.SDK.Generated");
        output.AppendLine("{");
        output.AppendLine($"    internal static class PluginJsonRegistration_{Hash(compilation.AssemblyName ?? "")}");
        output.AppendLine("    {");
        output.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        output.AppendLine("        internal static void Register()");
        output.AppendLine("        {");
        foreach (var name in codecs.CodecNames)
            output.AppendLine($"            {Sdk}PluginJson.Register({name}.Instance);");
        output.AppendLine("        }");
        output.AppendLine("    }");
        output.AppendLine("}");
        output.AppendLine();
        codecs.Emit(output);
        context.AddSource("PluginContracts.g.cs", output.ToString());
    }

    private sealed class ContractModel
    {
        public ContractModel(INamedTypeSymbol symbol, string? importedFrom)
        {
            Symbol = symbol;
            ImportedFrom = importedFrom;
        }

        public INamedTypeSymbol Symbol { get; }
        public string? ImportedFrom { get; }
        public List<MemberModel> Members { get; } = new();
    }

    private sealed class MemberModel
    {
        public MemberModel(IPropertySymbol property, string attribute, string name, List<TypeModel> types)
        {
            Property = property;
            Attribute = attribute;
            Name = name;
            Types = types;
        }

        public IPropertySymbol Property { get; }
        /// <summary>PluginService 或 PluginEvent。</summary>
        public string Attribute { get; }
        public string Name { get; }
        public List<TypeModel> Types { get; }
    }

    private static ContractModel? Contract(INamedTypeSymbol symbol, TypeCatalog catalog, SourceProductionContext context)
    {
        var location = symbol.Locations.FirstOrDefault();
        var partial = symbol.DeclaringSyntaxReferences.Any(reference =>
            reference.GetSyntax() is ClassDeclarationSyntax declaration && declaration.Modifiers.Any(SyntaxKind.PartialKeyword));
        if (!symbol.IsStatic || !partial || symbol.ContainingType is not null || symbol.IsGenericType)
        {
            context.ReportDiagnostic(Diagnostic.Create(GeneratorDiagnostics.ContractClass, location, symbol.Name));
            return null;
        }

        var importedFrom = symbol.GetAttributes()
            .First(attribute => attribute.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == Sdk + "PluginContractAttribute")
            .NamedArguments.FirstOrDefault(argument => argument.Key == "ImportedFrom").Value.Value as string;
        var contract = new ContractModel(symbol, importedFrom);

        foreach (var property in symbol.GetMembers().OfType<IPropertySymbol>())
        {
            var service = TypeCatalog.AttributeString(property, Sdk + "PluginServiceAttribute");
            var topic = TypeCatalog.AttributeString(property, Sdk + "PluginEventAttribute");
            if (service is null && topic is null) continue;
            var propertyLocation = property.Locations.FirstOrDefault() ?? location;
            var definition = property.Type is INamedTypeSymbol named ? named.OriginalDefinition.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) : "";
            var expected = topic is not null
                ? definition == Sdk + "PluginEvent<T>"
                : service!.EndsWith("*", System.StringComparison.Ordinal)
                    ? definition == Sdk + "PluginServiceFamily<TRequest, TResponse, TMetadata>"
                    : definition is Sdk + "PluginService<TRequest, TResponse>" or Sdk + "PluginService<TResponse>";
            var declaration = property.DeclaringSyntaxReferences.Select(reference => reference.GetSyntax()).OfType<PropertyDeclarationSyntax>().FirstOrDefault();
            var accessors = declaration?.AccessorList?.Accessors;
            var partialProperty = declaration is not null && declaration.Modifiers.Any(SyntaxKind.PartialKeyword)
                                  && accessors is { Count: 1 } && accessors.Value[0].Body is null && accessors.Value[0].ExpressionBody is null
                                  && accessors.Value[0].IsKind(SyntaxKind.GetAccessorDeclaration);
            if (!expected || !property.IsStatic || !partialProperty)
            {
                context.ReportDiagnostic(Diagnostic.Create(GeneratorDiagnostics.ContractProperty, propertyLocation, property.Name));
                continue;
            }

            var types = new List<TypeModel>();
            foreach (var argument in ((INamedTypeSymbol)property.Type).TypeArguments)
            {
                if (catalog.AddRoot(argument, propertyLocation) is { } type) types.Add(type);
            }
            if (types.Count == ((INamedTypeSymbol)property.Type).TypeArguments.Length)
                contract.Members.Add(new MemberModel(property, topic is null ? "PluginService" : "PluginEvent", topic ?? service!, types));
        }
        return contract;
    }

    private static void EmitImplementation(StringBuilder output, ContractModel contract, CodecEmitter codecs)
    {
        var ns = contract.Symbol.ContainingNamespace.IsGlobalNamespace ? null : contract.Symbol.ContainingNamespace.ToDisplayString();
        var indent = ns is null ? "" : "    ";
        if (ns is not null) output.AppendLine($"namespace {ns}").AppendLine("{");
        output.AppendLine($"{indent}static partial class {contract.Symbol.Name}");
        output.AppendLine($"{indent}{{");
        foreach (var member in contract.Members)
        {
            var type = member.Property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var field = "__shirobot_" + member.Property.Name;
            var arguments = string.Join(", ", new[] { SymbolDisplay.FormatLiteral(member.Name, true) }
                .Concat(member.Types.Select(t => codecs.CodecOf(t.Symbol) + ".Instance")));
            output.AppendLine($"{indent}    private static {type}? {field};");
            output.AppendLine($"{indent}    {Accessibility(member.Property.DeclaredAccessibility)} static partial {type} {member.Property.Name} {{ get => {field} ??= new({arguments}); }}");
        }
        output.AppendLine($"{indent}}}");
        if (ns is not null) output.AppendLine("}");
        output.AppendLine();
    }

    /// <summary>导出的契约源码：internal 的契约类和消息类型，命名空间不变，供其他插件编进自己的程序集。</summary>
    private static string ExportSource(List<ContractModel> contracts, TypeCatalog catalog, string assemblyName)
    {
        var types = new Dictionary<string, ITypeSymbol>();
        var stack = new Stack<TypeModel>(contracts.SelectMany(contract => contract.Members).SelectMany(member => member.Types));
        var seen = new HashSet<string>();
        while (stack.Count > 0)
        {
            var type = stack.Pop();
            if (!seen.Add(type.Key)) continue;
            if (type.Element is not null) stack.Push(type.Element);
            if (type.Kind is Shape.Enum or Shape.Object)
                types[type.Symbol.WithNullableAnnotation(NullableAnnotation.NotAnnotated).ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)] = type.Symbol;
            if (type.Kind == Shape.Object && catalog.ObjectOf(type.Symbol) is { } model)
                foreach (var property in model.Properties) stack.Push(property.Type);
        }

        var source = new StringBuilder();
        source.AppendLine(ContractStart);
        source.AppendLine("// <auto-generated/>");
        source.AppendLine($"// Plugin contract imported from {assemblyName}.");
        source.AppendLine("#nullable enable");
        foreach (var group in contracts.Select(contract => (Namespace: NamespaceOf(contract.Symbol), Text: ContractText(contract, assemblyName)))
                     .Concat(types.Values.Select(symbol => (Namespace: NamespaceOf(symbol), Text: TypeText(symbol, catalog))))
                     .GroupBy(item => item.Namespace))
        {
            source.AppendLine();
            if (group.Key is not null) source.AppendLine($"namespace {group.Key}").AppendLine("{");
            foreach (var item in group) source.Append(item.Text);
            if (group.Key is not null) source.AppendLine("}");
        }
        source.AppendLine(ContractEnd);
        return source.ToString();
    }

    private static string ContractText(ContractModel contract, string assemblyName)
    {
        var text = new StringBuilder();
        text.AppendLine($"    [{Sdk}PluginContract(ImportedFrom = {SymbolDisplay.FormatLiteral(assemblyName, true)})]");
        text.AppendLine($"    internal static partial class {contract.Symbol.Name}");
        text.AppendLine("    {");
        foreach (var member in contract.Members)
        {
            var type = member.Property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            text.AppendLine($"        [{Sdk}{member.Attribute}({SymbolDisplay.FormatLiteral(member.Name, true)})]");
            text.AppendLine($"        internal static partial {type} {member.Property.Name} {{ get; }}");
        }
        text.AppendLine("    }");
        return text.ToString();
    }

    private static string TypeText(ITypeSymbol symbol, TypeCatalog catalog)
    {
        var text = new StringBuilder();
        if (symbol.TypeKind == TypeKind.Enum && symbol is INamedTypeSymbol enumType)
        {
            var underlying = enumType.EnumUnderlyingType!.ToDisplayString();
            text.AppendLine($"    internal enum {symbol.Name} : {underlying}");
            text.AppendLine("    {");
            foreach (var field in enumType.GetMembers().OfType<IFieldSymbol>().Where(field => field.HasConstantValue))
                text.AppendLine($"        {field.Name} = {System.Convert.ToString(field.ConstantValue, System.Globalization.CultureInfo.InvariantCulture)},");
            text.AppendLine("    }");
            return text.ToString();
        }

        var model = catalog.ObjectOf(symbol)!;
        var kind = symbol.IsValueType ? "record struct" : "sealed record";
        var parameters = model.Constructor?.Parameters.Select(parameter =>
        {
            var property = model.Properties.FirstOrDefault(p => p.Parameter is not null && SymbolEqualityComparer.Default.Equals(p.Parameter, parameter));
            var name = property?.Name ?? parameter.Name;
            var type = parameter.Type.ToDisplayString(NullableFormat);
            var defaultValue = parameter.HasExplicitDefaultValue ? " = " + CodecEmitter.Literal(parameter.ExplicitDefaultValue, parameter.Type) : "";
            return PropertyAttributes(property, "property: ") + type + " " + name + defaultValue;
        }).ToList();
        text.Append($"    internal {kind} {symbol.Name}");
        if (parameters is { Count: > 0 }) text.Append("(" + string.Join(", ", parameters) + ")");
        text.AppendLine();
        text.AppendLine("    {");
        foreach (var property in model.Properties.Where(property => property.Parameter is null))
        {
            var type = property.Symbol.Type.ToDisplayString(NullableFormat);
            text.AppendLine($"        {PropertyAttributes(property, "")}public {(property.Symbol.IsRequired ? "required " : "")}{type} {property.Name} {{ get; init; }}");
        }
        text.AppendLine("    }");
        return text.ToString();
    }

    private static string PropertyAttributes(PropertyModel? property, string target)
    {
        if (property is null) return "";
        var attributes = new StringBuilder();
        if (property.Description is { } description)
            attributes.Append($"[{target}global::System.ComponentModel.Description({SymbolDisplay.FormatLiteral(description, true)})] ");
        if (TypeCatalog.AttributeString(property.Symbol, "global::System.Text.Json.Serialization.JsonPropertyNameAttribute") is { } jsonName)
            attributes.Append($"[{target}global::System.Text.Json.Serialization.JsonPropertyName({SymbolDisplay.FormatLiteral(jsonName, true)})] ");
        return attributes.ToString();
    }

    private static readonly SymbolDisplayFormat NullableFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier | SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    private static string? NamespaceOf(ISymbol symbol) =>
        symbol.ContainingNamespace is { IsGlobalNamespace: false } ns ? ns.ToDisplayString() : null;

    private static string Accessibility(Accessibility accessibility) => accessibility switch
    {
        Microsoft.CodeAnalysis.Accessibility.Public => "public",
        Microsoft.CodeAnalysis.Accessibility.Internal => "internal",
        Microsoft.CodeAnalysis.Accessibility.Private => "private",
        Microsoft.CodeAnalysis.Accessibility.Protected => "protected",
        Microsoft.CodeAnalysis.Accessibility.ProtectedOrInternal => "protected internal",
        Microsoft.CodeAnalysis.Accessibility.ProtectedAndInternal => "private protected",
        _ => "internal"
    };

    private static string Hash(string text)
    {
        unchecked
        {
            var hash = 2166136261u;
            foreach (var ch in text) hash = (hash ^ ch) * 16777619u;
            return hash.ToString("x8");
        }
    }
}
